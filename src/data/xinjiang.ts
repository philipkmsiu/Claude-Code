function day(
  theme: string,
  stayArea: string,
  mainPlan: string,
  paceNote: string,
  hotelDirection: string,
  spotIds: string[],
  tip: string,
  budget: string,
): DayPlan {
  return {
    theme,
    stayArea,
    stayCity: stayArea.replace(/市區|景區內|湖畔| overnight.*/, '').trim() || stayArea,
    mainPlan,
    paceNote,
    hotelDirection,
    schedule: [
      {
        time: '全日',
        title: mainPlan,
        detail: `${paceNote}｜住宿方向：${hotelDirection}`,
        spotId: spotIds[0],
      },
    ],
    budget,
    tip,
    spotIds,
  }
}

